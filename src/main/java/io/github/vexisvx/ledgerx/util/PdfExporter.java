package io.github.vexisvx.ledgerx.util;

import com.lowagie.text.*;
import com.lowagie.text.Font;
import com.lowagie.text.pdf.BaseFont;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import io.github.vexisvx.ledgerx.model.Transaction;

import java.awt.Color;
import java.io.File;
import java.io.FileOutputStream;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.List;

public class PdfExporter {

    private static BaseFont FA_FONT = null;
    private static boolean faFontTried = false;

    private static synchronized BaseFont getFaFont() {
        if (faFontTried) return FA_FONT;
        faFontTried = true;
        try {
            var in = PdfExporter.class.getResourceAsStream("/fonts/Vazirmatn-Regular.ttf");
            if (in != null) {
                byte[] bytes = in.readAllBytes();
                FA_FONT = BaseFont.createFont(
                    "Vazirmatn-Regular.ttf",
                    BaseFont.IDENTITY_H,
                    BaseFont.EMBEDDED,
                    true, bytes, null
                );
            }
        } catch (Exception e) {
            System.err.println("Could not load Persian font: " + e.getMessage());
        }
        return FA_FONT;
    }

    // Only reshape — no reversal (OpenPDF RTL does the rest)
    private static String fa(String text) {
        if (text == null || text.isEmpty()) return "";
        return ArabicReshaper.reshape(text);
    }

    public static void export(File file, List<Transaction> transactions, String language) throws Exception {
        boolean fa = "fa".equals(language);
        BaseFont faFont = fa ? getFaFont() : null;

        if (fa && faFont == null) {
            System.err.println("Persian font not available — falling back to English");
            fa = false;
        }

        Document doc = new Document(PageSize.A4, 36, 36, 36, 36);
        PdfWriter writer = PdfWriter.getInstance(doc, new FileOutputStream(file));
        doc.open();

        // Labels
        String title = fa ? fa("گزارش مالی LedgerX") : "LedgerX Financial Report";
        String dateLabel = fa ? fa("تاریخ") : "Date";
        String dateStr = LocalDate.now().format(DateTimeFormatter.ISO_DATE);

        String incomeLabel = fa ? fa("درآمد کل") : "Total Income";
        String expenseLabel = fa ? fa("هزینه کل") : "Total Expense";
        String netLabel = fa ? fa("موجودی خالص") : "Net Balance";
        String[] headers = fa
            ? new String[]{fa("تاریخ"), fa("نوع"), fa("عنوان"), fa("دسته"), fa("مبلغ")}
            : new String[]{"Date", "Type", "Title", "Category", "Amount"};
        String incomeText = fa ? fa("درآمد") : "Income";
        String expenseText = fa ? fa("هزینه") : "Expense";
        String footerText = fa
            ? fa("ایجاد شده با LedgerX توسط یونس احمدی")
            : "Generated by LedgerX — Younes Ahmadi";

        Font titleFont, headerFont, cellFont, smallFont, footerFont, summaryLabelFont, summaryValueFont;
        if (fa) {
            titleFont = new Font(faFont, 20, Font.BOLD, new Color(0, 150, 120));
            headerFont = new Font(faFont, 10, Font.BOLD, Color.WHITE);
            cellFont = new Font(faFont, 9, Font.NORMAL, Color.BLACK);
            smallFont = new Font(faFont, 10, Font.NORMAL, Color.DARK_GRAY);
            footerFont = new Font(faFont, 8, Font.ITALIC, Color.GRAY);
            summaryLabelFont = new Font(faFont, 9, Font.NORMAL, Color.GRAY);
            summaryValueFont = new Font(faFont, 14, Font.BOLD, new Color(0, 150, 120));
        } else {
            titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 20, new Color(0, 150, 120));
            headerFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, Color.WHITE);
            cellFont = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.BLACK);
            smallFont = FontFactory.getFont(FontFactory.HELVETICA, 10, Color.DARK_GRAY);
            footerFont = FontFactory.getFont(FontFactory.HELVETICA_OBLIQUE, 8, Color.GRAY);
            summaryLabelFont = FontFactory.getFont(FontFactory.HELVETICA, 9, Color.GRAY);
            summaryValueFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 14, new Color(0, 150, 120));
        }

        int runDir = fa ? PdfWriter.RUN_DIRECTION_RTL : PdfWriter.RUN_DIRECTION_LTR;

        // ─── Title (RTL for FA, LTR for EN) ───
        Paragraph p = new Paragraph(title, titleFont);
        p.setAlignment(fa ? Element.ALIGN_RIGHT : Element.ALIGN_CENTER);
        if (fa) p.setRunDirection(runDir);
        p.setSpacingAfter(20);
        doc.add(p);

        // ─── Date (RTL for FA, LTR for EN) ───
        Paragraph dateP = new Paragraph(
            dateLabel + (fa ? " " : ": ") + dateStr, smallFont);
        dateP.setAlignment(fa ? Element.ALIGN_RIGHT : Element.ALIGN_RIGHT);
        if (fa) dateP.setRunDirection(runDir);
        dateP.setSpacingAfter(15);
        doc.add(dateP);

        // ─── Summary ───
        BigDecimal totalIncome = BigDecimal.ZERO;
        BigDecimal totalExpense = BigDecimal.ZERO;
        for (Transaction t : transactions) {
            if (t.isIncome()) totalIncome = totalIncome.add(t.getAmount());
            else totalExpense = totalExpense.add(t.getAmount());
        }
        BigDecimal net = totalIncome.subtract(totalExpense);

        PdfPTable summary = new PdfPTable(3);
        summary.setWidthPercentage(100);
        summary.setSpacingAfter(20);
        if (fa) summary.setRunDirection(runDir);

        addSummaryCell(summary, incomeLabel, Formatter.money(totalIncome),
            new Color(0, 150, 120), summaryLabelFont, summaryValueFont, fa);
        addSummaryCell(summary, expenseLabel, Formatter.money(totalExpense),
            new Color(220, 60, 60), summaryLabelFont, summaryValueFont, fa);
        addSummaryCell(summary, netLabel, Formatter.money(net),
            new Color(60, 120, 220), summaryLabelFont, summaryValueFont, fa);
        doc.add(summary);

        // ─── Table ───
        PdfPTable table = new PdfPTable(5);
        table.setWidthPercentage(100);
        table.setWidths(new float[]{15, 15, 30, 20, 20});
        if (fa) table.setRunDirection(runDir);

        for (String h : headers) {
            PdfPCell cell = new PdfPCell(new Phrase(h, headerFont));
            cell.setBackgroundColor(new Color(0, 150, 120));
            cell.setPadding(8);
            cell.setHorizontalAlignment(Element.ALIGN_CENTER);
            cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
            if (fa) cell.setRunDirection(runDir);
            table.addCell(cell);
        }

        int row = 0;
        for (Transaction t : transactions) {
            Color bg = row % 2 == 0 ? Color.WHITE : new Color(245, 245, 245);

            // Date (digits) — LTR always
            addCell(table, t.getDate().toString(), cellFont, bg,
                Element.ALIGN_CENTER, PdfWriter.RUN_DIRECTION_LTR);

            // Type
            addCell(table, t.isIncome() ? incomeText : expenseText, cellFont, bg,
                Element.ALIGN_CENTER, runDir);

            // Title
            String titleText = fa ? fa(t.getTitle()) : t.getTitle();
            addCell(table, titleText, cellFont, bg,
                fa ? Element.ALIGN_RIGHT : Element.ALIGN_LEFT, runDir);

            // Category
            String cat = t.getCategoryName() != null ? t.getCategoryName() : "-";
            String catText = fa ? fa(cat) : cat;
            addCell(table, catText, cellFont, bg,
                fa ? Element.ALIGN_RIGHT : Element.ALIGN_LEFT, runDir);

            // Amount — LTR always
            addCell(table, Formatter.money(t.getAmount()), cellFont, bg,
                Element.ALIGN_RIGHT, PdfWriter.RUN_DIRECTION_LTR);

            row++;
        }
        doc.add(table);

        // ─── Footer ───
        doc.add(new Paragraph(" "));
        Paragraph footer = new Paragraph(footerText, footerFont);
        footer.setAlignment(fa ? Element.ALIGN_RIGHT : Element.ALIGN_CENTER);
        if (fa) footer.setRunDirection(runDir);
        doc.add(footer);

        doc.close();
    }

    private static void addSummaryCell(PdfPTable table, String label, String value,
                                        Color valueColor, Font labelFont, Font valueFont,
                                        boolean fa) {
        Font coloredValue = new Font(valueFont.getBaseFont(), valueFont.getSize(),
            valueFont.getStyle(), valueColor);

        PdfPCell cell = new PdfPCell();
        cell.setPadding(12);
        cell.setBackgroundColor(new Color(250, 250, 250));
        cell.setBorder(Rectangle.BOX);
        cell.setBorderColor(new Color(220, 220, 220));
        if (fa) cell.setRunDirection(PdfWriter.RUN_DIRECTION_RTL);

        Paragraph lp = new Paragraph(label, labelFont);
        lp.setAlignment(Element.ALIGN_CENTER);
        Paragraph vp = new Paragraph(value, coloredValue);
        vp.setAlignment(Element.ALIGN_CENTER);

        cell.addElement(lp);
        cell.addElement(vp);
        table.addCell(cell);
    }

    private static void addCell(PdfPTable table, String text, Font font, Color bg,
                                 int align, int runDir) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font));
        cell.setBackgroundColor(bg);
        cell.setPadding(6);
        cell.setHorizontalAlignment(align);
        cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        cell.setBorderColor(new Color(220, 220, 220));
        cell.setRunDirection(runDir);
        table.addCell(cell);
    }
}
